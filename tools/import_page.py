"""Copy the TrailsBI report page into the visual as src/generated/page.ts.

The visual shows the same page the trailsbi command writes, so its markup, styles
and script come straight from the trailsbi package rather than being kept twice.
Run this after upgrading trailsbi:

    python tools/import_page.py                     # uses the installed trailsbi
    python tools/import_page.py --src ../trailsbi/src   # or a checkout of the repo

Placeholders the page fills from the project (__TITLE__, __BOOT__, __DATA__) are left
for the visual to fill at run time; everything else is filled here.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "generated" / "page.ts"
RUNTIME = {"TITLE", "BOOT", "DATA"}


def between(text: str, start: str, end: str) -> str:
    i = text.index(start) + len(start)
    return text[i:text.index(end, i)]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--src", help="path to a trailsbi checkout's src folder (default: the installed package)")
    args = ap.parse_args()
    if args.src:
        sys.path.insert(0, str(Path(args.src).resolve()))

    from trailsbi import brand, icons, render

    html = render.page_template()
    values = {
        "FAVICON": brand.FAVICON,
        "MARKVB": brand.MARK_VB,
        "MARK": brand.MARK_SVG,
        "LOGOVB": brand.LOGO_VB,
        "LOGO": brand.LOGO_SVG,
        "TAGLINE": brand.TAGLINE,
        "VERSION": brand.VERSION,
    }

    def fill(part: str) -> str:
        def sub(m: re.Match) -> str:
            key = m.group(1)
            if key in RUNTIME:
                return m.group(0)
            if key not in values:
                raise SystemExit(f"Unknown placeholder __{key}__ in the TrailsBI page")
            return values[key]

        return re.sub(r"__([A-Z]+)__", sub, part)

    css = between(html, "<style>", "</style>")
    body = between(html, "<body>\n", '<script id="icons"')
    script = between(html, '"use strict";\n', "})();\n</script>")
    script = fill(script)
    if re.search(r"__[A-Z]+__", script):
        raise SystemExit("A placeholder was left in the page script")
    for name in ("dxDownload", "switchTab", "openTab", "toast"):
        if f"function {name}(" not in script:
            raise SystemExit(f"The page no longer defines {name}(); update the hooks in tools/import_page.py")

    icons_js = json.dumps(json.dumps(icons.ICONS).replace("<", "\\u003c"))
    module = f"""// @ts-nocheck
/* eslint-disable */
/* Generated by tools/import_page.py from trailsbi {brand.VERSION}. Do not edit by hand. */

export const TRAILSBI_VERSION = {json.dumps(brand.VERSION)};
export const PAGE_CSS = {json.dumps(fill(css))};
export const PAGE_BODY = {json.dumps(fill(body))};
export const PAGE_ICONS = {icons_js};

/** Runs the TrailsBI page script against the markup already in the document.
 *  hooks.download(name, blob, toast) replaces the page's own file download.
 *  hooks.canOpen(view) decides whether a view may open; when it says no,
 *  hooks.blocked(view, toast) is told instead. Returns {{ open(view), current() }}. */
export function runPage(hooks) {{
"use strict";
{script}
if (hooks && hooks.download) {{
  dxDownload = function (name, blob) {{ hooks.download(name, blob, toast); }};
}}
var openView = switchTab;
if (hooks && hooks.canOpen) {{
  switchTab = function (name) {{
    if (hooks.canOpen(name)) openView(name);
    else if (hooks.blocked) hooks.blocked(name, toast);
  }};
}}
return {{ open: function (name) {{ openView(name); }}, current: openTab }};
}}
"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(module, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} from trailsbi {brand.VERSION} ({OUT.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
